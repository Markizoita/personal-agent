create table notes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  text text not null,
  tags text[] not null default '{}',
  updated_at timestamptz not null default now()
);

grant all on table public.notes to service_role;
grant usage, select on all sequences in schema public to service_role;

create table pending_note_delete (
  id bigint generated by default as identity primary key,
  note_id bigint not null,
  created_at timestamptz not null default now()
);

grant all on table public.pending_note_delete to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function save_note(p_text text, p_tags text[])
returns jsonb
language plpgsql
as $$
declare
  v_id bigint;
begin
  insert into notes (text, tags) values (p_text, p_tags) returning id into v_id;
  return jsonb_build_object('id', v_id, 'tags', p_tags);
end;
$$;

create or replace function search_notes(p_query text default null, p_limit int default 10)
returns jsonb
language plpgsql
as $$
declare
  v_query text;
  v_result jsonb;
begin
  v_query := nullif(nullif(trim(p_query), ''), 'null');

  if v_query is null then
    select coalesce(jsonb_agg(jsonb_build_object('id', id, 'created_at', created_at, 'text', text, 'tags', tags) order by created_at desc), '[]'::jsonb)
    into v_result
    from (select * from notes order by created_at desc limit p_limit) s;
  else
    select coalesce(jsonb_agg(jsonb_build_object('id', id, 'created_at', created_at, 'text', text, 'tags', tags) order by created_at desc), '[]'::jsonb)
    into v_result
    from notes
    where text ilike '%' || v_query || '%'
       or exists (select 1 from unnest(tags) t where t ilike '%' || v_query || '%')
    limit p_limit;
  end if;

  return jsonb_build_object('items', v_result);
end;
$$;

create or replace function edit_note(p_id bigint, p_text text default null, p_tags text[] default null)
returns jsonb
language plpgsql
as $$
begin
  update notes
  set text = coalesce(nullif(nullif(trim(p_text), ''), 'null'), text),
      tags = coalesce(p_tags, tags),
      updated_at = now()
  where id = p_id;

  return (select jsonb_build_object('id', id, 'text', text, 'tags', tags) from notes where id = p_id);
end;
$$;

create or replace function set_pending_note_delete(p_note_id bigint)
returns jsonb
language plpgsql
as $$
begin
  delete from pending_note_delete where true;
  insert into pending_note_delete (note_id) values (p_note_id);
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function get_pending_note_delete()
returns jsonb
language sql
as $$
  select coalesce(
    (select jsonb_build_object('pending', true, 'note_id', note_id)
     from pending_note_delete
     where created_at >= now() - interval '10 minutes'
     order by created_at desc limit 1),
    jsonb_build_object('pending', false)
  );
$$;

create or replace function delete_note(p_id bigint)
returns jsonb
language plpgsql
as $$
declare
  v_text text;
begin
  select text into v_text from notes where id = p_id;
  delete from notes where id = p_id;
  delete from pending_note_delete where true;
  return jsonb_build_object('ok', true, 'id', p_id, 'text', v_text);
end;
$$;

grant execute on function save_note, search_notes, edit_note, set_pending_note_delete, get_pending_note_delete, delete_note to service_role;
