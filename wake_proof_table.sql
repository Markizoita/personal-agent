create table wake_proof (
  id bigint generated by default as identity primary key,
  log_date date unique not null,
  passage_text text,
  passage_source text,
  sent_at timestamptz,
  reply_1_text text,
  reply_1_at timestamptz,
  reply_1_passed boolean,
  reply_2_text text,
  reply_2_at timestamptz,
  reply_2_passed boolean,
  result text,
  streak_current int,
  streak_best int,
  updated_at timestamptz not null default now()
);

grant all on table public.wake_proof to service_role;
grant usage, select on all sequences in schema public to service_role;
