create table tiktok_sessions (
  id bigint generated by default as identity primary key,
  open_at timestamptz not null,
  close_at timestamptz,
  created_at timestamptz not null default now()
);

grant all on table public.tiktok_sessions to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function log_tiktok_open()
returns jsonb
language plpgsql
as $$
declare
  v_last_open timestamptz;
begin
  select max(open_at) into v_last_open from tiktok_sessions;
  if v_last_open is not null and abs(extract(epoch from (now() - v_last_open))) < 5 then
    return jsonb_build_object('ok', true, 'note', 'duplicate ignored');
  end if;

  insert into tiktok_sessions (open_at) values (now());
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function log_tiktok_close()
returns jsonb
language plpgsql
as $$
declare
  v_pending_id bigint;
  v_last_close timestamptz;
begin
  select max(close_at) into v_last_close from tiktok_sessions where close_at is not null;
  if v_last_close is not null and abs(extract(epoch from (now() - v_last_close))) < 5 then
    return jsonb_build_object('ok', true, 'note', 'duplicate ignored');
  end if;

  select id into v_pending_id from tiktok_sessions where close_at is null order by open_at desc limit 1;
  if v_pending_id is null then
    return jsonb_build_object('ok', false, 'note', 'no pending open session to close');
  end if;

  update tiktok_sessions set close_at = now() where id = v_pending_id;
  return jsonb_build_object('ok', true, 'id', v_pending_id);
end;
$$;

create or replace function get_tiktok_minutes_for_date(p_date date)
returns jsonb
language plpgsql
as $$
declare
  v_day_start timestamptz;
  v_day_end timestamptz;
  v_total numeric := 0;
  v_session record;
  v_effective_close timestamptz;
  v_overlap_start timestamptz;
  v_overlap_end timestamptz;
  v_session_count int := 0;
begin
  v_day_start := p_date::timestamp at time zone 'America/New_York';
  v_day_end := v_day_start + interval '1 day';

  for v_session in
    select * from tiktok_sessions
    where open_at < v_day_end
      and coalesce(close_at, least(now(), open_at + interval '20 minutes')) > v_day_start
  loop
    v_effective_close := coalesce(v_session.close_at, least(now(), v_session.open_at + interval '20 minutes'));
    v_overlap_start := greatest(v_session.open_at, v_day_start);
    v_overlap_end := least(v_effective_close, v_day_end);
    if v_overlap_end > v_overlap_start then
      v_total := v_total + extract(epoch from (v_overlap_end - v_overlap_start)) / 60.0;
      v_session_count := v_session_count + 1;
    end if;
  end loop;

  return jsonb_build_object('minutes', round(v_total), 'sessions', v_session_count);
end;
$$;

create or replace function get_tiktok_week()
returns jsonb
language plpgsql
as $$
declare
  v_today date;
  v_day date;
  v_result jsonb := '[]'::jsonb;
  v_day_info jsonb;
begin
  v_today := (now() at time zone 'America/New_York')::date;

  for i in 0..6 loop
    v_day := v_today - i;
    v_day_info := get_tiktok_minutes_for_date(v_day);
    v_result := v_result || jsonb_build_array(jsonb_build_object('date', v_day, 'minutes', v_day_info->'minutes'));
  end loop;

  return jsonb_build_object('days', v_result);
end;
$$;

grant execute on function log_tiktok_open, log_tiktok_close, get_tiktok_minutes_for_date, get_tiktok_week to service_role;
