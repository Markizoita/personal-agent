create table conversation_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null,
  role text not null,
  content text not null,
  created_at timestamptz not null default now()
);

grant all on table public.conversation_messages to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function save_conversation_turn(p_chat_id bigint, p_user_text text, p_assistant_text text)
returns jsonb
language plpgsql
as $$
begin
  insert into conversation_messages (chat_id, role, content) values (p_chat_id, 'user', p_user_text);
  insert into conversation_messages (chat_id, role, content) values (p_chat_id, 'assistant', p_assistant_text);
  return jsonb_build_object('ok', true);
end;
$$;

create or replace function get_recent_conversation(p_chat_id bigint, p_limit int default 20)
returns jsonb
language sql
as $$
  select coalesce(jsonb_agg(jsonb_build_object('role', role, 'content', content) order by created_at), '[]'::jsonb)
  from (select * from conversation_messages where chat_id = p_chat_id order by created_at desc limit p_limit) s;
$$;

grant execute on function save_conversation_turn, get_recent_conversation to service_role;
