-- Backlog of "I want this changed" notes sent from Telegram with /tweak.
-- Reviewed and fixed in Claude Code sessions, then marked done.
create table if not exists tweaks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  note text not null,
  context text,                      -- text of the bot message being replied to, if any
  status text not null default 'open' check (status in ('open', 'done', 'dropped')),
  resolution text,                   -- what was changed (filled in when closed)
  resolved_at timestamptz
);

grant all on table public.tweaks to service_role;
grant usage, select on all sequences in schema public to service_role;
