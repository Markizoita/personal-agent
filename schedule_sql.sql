create table schedule_items (
  id bigint generated by default as identity primary key,
  log_date date not null,
  title text not null,
  start_time time not null,
  end_time time,
  place text,
  check_at time not null,
  status text not null default 'pending',
  what_happened text,
  pinged boolean not null default false,
  checked_at timestamptz,
  created_at timestamptz not null default now()
);

grant all on table public.schedule_items to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function set_schedule(p_log_date date, p_items jsonb)
returns jsonb
language plpgsql
as $$
declare
  v_item jsonb;
  v_start time;
  v_end time;
begin
  delete from schedule_items where log_date = p_log_date;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_start := (v_item->>'start_time')::time;
    v_end := nullif(v_item->>'end_time', '')::time;
    insert into schedule_items (log_date, title, start_time, end_time, place, check_at)
    values (
      p_log_date,
      v_item->>'title',
      v_start,
      v_end,
      nullif(v_item->>'place', ''),
      coalesce(v_end, v_start + interval '1 hour')
    );
  end loop;

  return (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', id, 'title', title, 'start_time', start_time, 'end_time', end_time,
      'place', place, 'status', status, 'what_happened', what_happened
    ) order by start_time), '[]'::jsonb)
    from schedule_items where log_date = p_log_date
  );
end;
$$;

create or replace function check_schedule_item(p_id bigint, p_status text, p_what_happened text default null)
returns jsonb
language plpgsql
as $$
begin
  update schedule_items
  set status = p_status,
      what_happened = nullif(nullif(trim(p_what_happened), ''), 'null'),
      checked_at = now()
  where id = p_id;

  return (select jsonb_build_object('id', id, 'title', title, 'status', status, 'what_happened', what_happened)
          from schedule_items where id = p_id);
end;
$$;

create or replace function get_due_schedule_pings()
returns jsonb
language plpgsql
as $$
declare
  v_today date;
  v_now time;
  v_result jsonb;
  v_quiet boolean;
begin
  v_today := (now() at time zone 'America/New_York')::date;
  v_now := (now() at time zone 'America/New_York')::time;
  v_quiet := (v_now >= time '22:30' or v_now < time '07:00');

  if v_quiet then
    return '[]'::jsonb;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', id, 'title', title, 'start_time', start_time, 'end_time', end_time, 'place', place
  )), '[]'::jsonb)
  into v_result
  from schedule_items
  where log_date = v_today
    and status = 'pending'
    and pinged = false
    and check_at <= v_now
    and not (
      abs(extract(epoch from (check_at - time '08:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '14:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '17:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '22:00'))) <= 900
    );

  update schedule_items set pinged = true
  where log_date = v_today
    and status = 'pending'
    and pinged = false
    and check_at <= v_now
    and not (
      abs(extract(epoch from (check_at - time '08:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '14:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '17:00'))) <= 900 or
      abs(extract(epoch from (check_at - time '22:00'))) <= 900
    );

  return v_result;
end;
$$;

create or replace function get_daily_form(p_log_date date)
returns jsonb
language plpgsql
as $$
declare
  v_log daily_log%rowtype;
  v_wake jsonb;
  v_spending_total numeric;
  v_spending_items jsonb;
  v_schedule_items jsonb;
  v_day_start timestamptz;
  v_day_end timestamptz;
begin
  v_day_start := p_log_date::timestamp at time zone 'America/New_York';
  v_day_end := v_day_start + interval '1 day';

  select * into v_log from daily_log where log_date = p_log_date;

  select jsonb_build_object('result', result, 'streak_current', streak_current, 'streak_best', streak_best)
  into v_wake from wake_proof where log_date = p_log_date;

  select coalesce(sum(amount), 0) into v_spending_total
  from spending where created_at >= v_day_start and created_at < v_day_end;

  select coalesce(jsonb_agg(jsonb_build_object('merchant', merchant, 'amount', amount, 'category', category) order by created_at), '[]'::jsonb)
  into v_spending_items
  from spending where created_at >= v_day_start and created_at < v_day_end;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', id, 'title', title, 'start_time', start_time, 'end_time', end_time,
    'place', place, 'check_at', check_at, 'status', status, 'what_happened', what_happened
  ) order by start_time), '[]'::jsonb)
  into v_schedule_items
  from schedule_items where log_date = p_log_date;

  return jsonb_build_object(
    'log_date', p_log_date,
    'sleep_hours', v_log.sleep_hours,
    'food', coalesce(v_log.food, '[]'::jsonb),
    'gym_done', v_log.gym_done,
    'gym_note', v_log.gym_note,
    'mood', v_log.mood,
    'mood_note', v_log.mood_note,
    'start_build_hours', v_log.start_build_hours,
    'start_plan_hours', v_log.start_plan_hours,
    'start_proof', v_log.start_proof,
    'wake', coalesce(v_wake, 'null'::jsonb),
    'spending_total', v_spending_total,
    'spending_items', v_spending_items,
    'schedule_items', v_schedule_items,
    'tiktok_minutes', null
  );
end;
$$;

grant execute on function set_schedule, check_schedule_item, get_due_schedule_pings, get_daily_form to service_role;
