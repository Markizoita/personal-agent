create table learned_items (
  id bigint generated by default as identity primary key,
  title text not null,
  type text not null,
  total numeric,
  current numeric not null default 0,
  status text not null default 'in_progress',
  takeaway text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table learned_log (
  id bigint generated by default as identity primary key,
  item_id bigint not null references learned_items(id) on delete cascade,
  delta numeric not null,
  created_at timestamptz not null default now()
);

grant all on table public.learned_items to service_role;
grant all on table public.learned_log to service_role;
grant usage, select on all sequences in schema public to service_role;

create or replace function find_learned_item(p_query text)
returns jsonb
language sql
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', id, 'title', title, 'type', type, 'total', total, 'current', current, 'status', status
  ) order by updated_at desc), '[]'::jsonb)
  from learned_items
  where title ilike '%' || p_query || '%';
$$;

create or replace function create_learned_item(p_title text, p_type text, p_total text default null, p_initial text default null)
returns jsonb
language plpgsql
as $$
declare
  v_total numeric;
  v_initial numeric;
  v_id bigint;
begin
  v_total := nullif(nullif(trim(p_total), ''), 'null')::numeric;
  v_initial := coalesce(nullif(nullif(trim(p_initial), ''), 'null')::numeric, 0);

  insert into learned_items (title, type, total, current)
  values (p_title, p_type, v_total, v_initial)
  returning id into v_id;

  if v_initial > 0 then
    insert into learned_log (item_id, delta) values (v_id, v_initial);
  end if;

  return (select jsonb_build_object('id', id, 'title', title, 'type', type, 'total', total, 'current', current) from learned_items where id = v_id);
end;
$$;

create or replace function update_learned_progress(p_item_id bigint, p_mode text, p_value numeric, p_takeaway text default null)
returns jsonb
language plpgsql
as $$
declare
  v_old numeric;
  v_new numeric;
  v_delta numeric;
  v_clean_takeaway text;
begin
  select current into v_old from learned_items where id = p_item_id;
  v_clean_takeaway := nullif(nullif(trim(p_takeaway), ''), 'null');

  if p_mode = 'add' then
    v_delta := p_value;
    v_new := v_old + p_value;
  else
    v_new := p_value;
    v_delta := p_value - v_old;
  end if;

  update learned_items
  set current = v_new,
      takeaway = coalesce(v_clean_takeaway, takeaway),
      updated_at = now()
  where id = p_item_id;

  insert into learned_log (item_id, delta) values (p_item_id, v_delta);

  return (select jsonb_build_object('id', id, 'title', title, 'type', type, 'total', total, 'current', current, 'takeaway', takeaway) from learned_items where id = p_item_id);
end;
$$;

create or replace function finish_learned_item(p_item_id bigint)
returns jsonb
language plpgsql
as $$
begin
  update learned_items set status = 'finished', updated_at = now() where id = p_item_id;
  return (select jsonb_build_object('id', id, 'title', title) from learned_items where id = p_item_id);
end;
$$;

create or replace function get_bookmarks()
returns jsonb
language sql
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', id, 'title', title, 'type', type, 'total', total, 'current', current,
    'last_updated_label', case
      when (updated_at at time zone 'America/New_York')::date = (now() at time zone 'America/New_York')::date then 'today'
      when (updated_at at time zone 'America/New_York')::date = ((now() at time zone 'America/New_York')::date - 1) then 'yesterday'
      else ((now() at time zone 'America/New_York')::date - (updated_at at time zone 'America/New_York')::date)::text || ' days ago'
    end
  ) order by updated_at desc), '[]'::jsonb)
  from learned_items
  where status = 'in_progress';
$$;

create or replace function get_learned_week()
returns jsonb
language plpgsql
as $$
declare
  v_week_start timestamptz;
  v_podcast_minutes numeric;
  v_pages numeric;
  v_finished jsonb;
begin
  v_week_start := ((now() at time zone 'America/New_York')::date - 6)::timestamp at time zone 'America/New_York';

  select coalesce(sum(l.delta), 0) into v_podcast_minutes
  from learned_log l join learned_items i on i.id = l.item_id
  where i.type = 'podcast' and l.created_at >= v_week_start;

  select coalesce(sum(l.delta), 0) into v_pages
  from learned_log l join learned_items i on i.id = l.item_id
  where i.type = 'book' and l.created_at >= v_week_start;

  select coalesce(jsonb_agg(title), '[]'::jsonb) into v_finished
  from learned_items
  where status = 'finished' and updated_at >= v_week_start;

  return jsonb_build_object('podcast_minutes', v_podcast_minutes, 'pages', v_pages, 'finished', v_finished);
end;
$$;

grant execute on function find_learned_item, create_learned_item, update_learned_progress, finish_learned_item, get_bookmarks, get_learned_week to service_role;
